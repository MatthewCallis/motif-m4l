import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const directory = path.resolve('motifs/builtin');
const files = (await readdir(directory)).filter((file) => file.endsWith('.json')).sort();
const motifs = [];
for (const file of files) {
  motifs.push(JSON.parse(await readFile(path.join(directory, file), 'utf8')));
}

const output = `// Generated by scripts/generate-builtins.mjs.\nimport type { Motif } from '../core/types.js';\n\nexport const BUILTIN_MOTIFS = ${JSON.stringify(motifs, null, 2)} as const satisfies readonly Motif[];\n`;
await writeFile('src/generated/builtins.ts', output);
